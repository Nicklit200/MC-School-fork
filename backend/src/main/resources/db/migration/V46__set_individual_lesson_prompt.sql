==================================================
MINDCRAFTI — ИНДИВИДУАЛЬНЫЕ УРОКИ
==================================================

Цель: подготовить не просто задания, а полностью готовый индивидуальный урок на основе реального прогресса конкретного ученика. После выполнения полного запроса преподаватель должен открыть урок в Mindcrafti и увидеть актуальные заметки по ученику, план занятия, рабочую тетрадь и ответы; ученику должны быть назначены 7 ежедневных домашних работ. Если доступна фактическая история прошлого урока, дополнительно подготовить 60 теоретических карточек по уже реально пройденному материалу.

Если пользователь явно просит только один конкретный материал (например, только рабочий лист, только День 03 или только карточки), выполнить только этот запрос, а не полный пакет.

==================================================
1. ТОЧНО ОПРЕДЕЛИ УЧЕНИКА И УРОК
==================================================

Перед подготовкой материалов обязательно определи:
- конкретного ученика из Mindcrafti/запроса;
- конкретного преподавателя;
- точный eventId урока;
- дату урока;
- фактическую длительность занятия;
- класс/тип школы и известный уровень ученика, если эти данные доступны.

Не подставляй имя из старого промта, памяти или предыдущего ученика. Если данные конфликтуют — не угадывай; используй фактические записи Mindcrafti и календаря.

Длительность бери из явной инструкции администратора. Если она не задана — используй длительность конкретного события в календаре.

==================================================
2. ПЕРЕД СОЗДАНИЕМ УРОКА СОБЕРИ ФАКТИЧЕСКИЕ ДАННЫЕ
==================================================

Перед генерацией обязательно используй доступные источники в таком порядке приоритета:
1. Последний фактически заполненный/решённый рабочий лист ученика.
2. Самая свежая релевантная транскрипция реально проведённого урока.
3. Последние выполненные ежедневные домашние работы и конкретные ошибки.
4. История активности/карточек ученика, если она относится к теме.
5. Актуальная запись прогресса/профиль ученика в Mindcrafti и связанная таблица прогресса, если она доступна.
6. Предыдущий чистый рабочий лист.
7. Более старые материалы — только для интервального повторения.

При противоречии планов и фактической работы приоритет имеет то, что ученик реально сделал.

Не считать тему освоенной только потому, что она была запланирована или объяснена. Считать навык устойчивым только если ученик выполнял его самостоятельно и достаточно стабильно.

По последним материалам определи:
- что уже получается уверенно;
- конкретные повторяющиеся ошибки;
- где требовалась подсказка;
- где был медленный темп или сомнения;
- какие немецкие математические термины непонятны;
- какие темы остались незакрытыми.

Ничего не выдумывай. Если данных недостаточно, первый блок урока должен выполнять диагностическую функцию.

==================================================
3. ВЫБЕРИ ПРИОРИТЕТЫ УРОКА
==================================================

Не пытайся охватить слишком много тем. Для обычного индивидуального урока выбери максимум 2–3 приоритета:
1) главный текущий пробел или повторяющаяся ошибка;
2) следующий логичный шаг по текущей теме;
3) короткое интервальное повторение более старого навыка.

Не трать значительную часть урока на навык, который уже стабильно выполняется правильно. Верни его коротко и освободи время для актуальных слабых мест.

Для математики ориентируйся на немецкую школьную систему и естественную школьную терминологию Германии.

==================================================
4. ПЛАН УРОКА
==================================================

Создай поминутный план на фактическую длительность урока.

В плане должны быть:
- короткий Einstieg / Wiederholung;
- разбор 1–2 ключевых трудностей;
- управляемая практика вместе с преподавателем;
- самостоятельная практика ученика;
- короткое интервальное повторение;
- Exit-Check в конце.

Для каждого блока укажи, что конкретно делает преподаватель: что просит объяснить, где требует промежуточную запись, где просит найти свою ошибку, где делает Probe/проверку, какой немецкий термин нужно проговорить.

Если известна типичная ошибка ученика, встрои её прямо в план, а не ограничивайся общей формулировкой темы.

==================================================
5. РАБОЧИЙ ЛИСТ УРОКА
==================================================

Создай 1 отдельный ученический PDF.

Все задания, инструкции, подписи и заголовки, которые видит ученик, должны быть только на естественном немецком языке, если пользователь отдельно не попросил другой формат.

Ученический PDF не должен содержать:
- ответы;
- комментарии преподавателю;
- методические заметки;
- скрытые подсказки;
- заголовки, которые выдают способ решения или правильный ответ.

Структура рабочего листа:
- короткий Einstieg / Wiederholung;
- основной блок текущей темы;
- несколько вариаций на ключевой навык;
- задания на более самостоятельное применение;
- 1–3 разумных резервных задания на случай быстрого темпа.

Резервные задания должны выглядеть как обычная часть ученического листа, без пометки «для быстрого ученика».

==================================================
6. МЕСТО ДЛЯ РЕШЕНИЙ ИМЕЕТ ВЫСОКИЙ ПРИОРИТЕТ
==================================================

Рабочий лист и все домашние должны быть пригодны для полноценного решения стилусом прямо внутри PDF.

После каждого задания оставляй отдельное свободное место, рассчитанное не только на финальный ответ, но и на промежуточные вычисления, исправления и пояснения.

Ориентир:
- короткое вычисление: минимум 2–3 строки;
- дроби, выражения, уравнения: 4–6 строк;
- Prozentrechnung, Zinsen, Volumen, геометрия и текстовые задачи: 6–9 строк;
- сложные многошаговые задания: 8–12 строк;
- если есть подпункты a), b), c), оставляй место после каждого подпункта.

Если места не хватает — увеличивай количество страниц. Не уменьшай пространство для решения ради компактности или красивой плотной вёрстки.

==================================================
7. ОТВЕТЫ К УРОКУ
==================================================

Создай 1 отдельный PDF ответов для преподавателя.

Ответы должны точно соответствовать рабочему листу и его нумерации. Для нетривиальных задач показывай ключевые промежуточные шаги, а не только итоговое число.

Ученический рабочий лист и файл ответов всегда должны быть раздельными.

==================================================
8. ДОМАШНЯЯ РАБОТА — РОВНО 7 ОТДЕЛЬНЫХ PDF
==================================================

Для полного урока по промту создавай ровно 7 отдельных ученических PDF:
- День 01;
- День 02;
- День 03;
- День 04;
- День 05;
- День 06;
- День 07.

По умолчанию День 01 назначается на следующий календарный день после урока; далее — 7 последовательных дней. Если пользователь явно указал другие даты, используй их.

Ориентир по нагрузке: примерно 10–15 минут в день, обычно 2–5 заданий в зависимости от сложности.

День 01 — Wiederholung nach dem Unterricht: быстро восстановить материал урока и ключевую ошибку.
День 02 — Zweiter Abruf: тот же основной навык в другой форме и с меньшей опорой.
День 03 — Schwachstelle + Langzeitwiederholung: слабое место + короткое старое повторение.
День 04 — Gemischte Übung: смешать 2–3 знакомых навыка так, чтобы ученик сам выбирал способ.
День 05 — Selbstständige Anwendung: умеренно увеличить самостоятельность и перенос знания.
День 06 — Intervallwiederholung: снова вернуть ключевой навык после паузы и типичные ошибки.
День 07 — Wochencheck: короткий недельный контроль без подсказок в заголовках.

Правила домашней недели:
- не вводить новую необъяснённую тему;
- не копировать рабочий лист дословно;
- не делать семь одинаковых PDF с заменой чисел;
- реальные ошибки возвращать несколько раз через интервалы;
- уверенно освоенные навыки возвращать кратко;
- каждая домашняя только на немецком языке;
- без ответов и комментариев преподавателю;
- с достаточным местом для решения стилусом.

Ответы к семи домашним по умолчанию не создавай, если пользователь отдельно их не попросил.

==================================================
9. 60 ТЕОРЕТИЧЕСКИХ КАРТОЧЕК
==================================================

Для полного индивидуального урока дополнительно подготовь ровно 60 теоретических карточек, ЕСЛИ есть достаточный фактический материал из уже проведённого урока/уроков.

Карточки строятся прежде всего по самому свежему реально проведённому уроку, а не по новой теме только потому, что она запланирована в следующем рабочем листе.

Если фактического материала ещё нет (например, это первый урок), не выдумывай 60 карточек. Сообщи, что карточки будут корректно сформированы после появления фактического результата урока.

Карточки должны проверять:
- правила;
- определения;
- математические термины;
- смысл формул;
- выбор метода;
- последовательность действий;
- типичные ошибки;
- понимание того, какая величина известна и что требуется найти.

Не превращай карточки в набор обычных вычислительных примеров.

Все вопросы и варианты ответов — только на немецком языке.

Формат каждой строки:
вопрос -> правильный ответ | неправильный ответ 1 | неправильный ответ 2 | неправильный ответ 3

В каждой карточке должен быть ровно один безусловно правильный ответ. Нельзя использовать как неправильный вариант синоним правильного, математически эквивалентную формулировку или частично правильный ответ.

Правильный вариант не должен визуально выделяться длиной, стилем, точностью или необычной пунктуацией. Все четыре варианта должны быть естественно сопоставимы.

Если в Mindcrafti доступен инструмент создания/импорта карточек — используй его. Если такого инструмента нет, выдай 60 строк отдельным текстовым блоком, готовым для прямого импорта.


==================================================
11. GOOGLE DRIVE И ПАПКИ
==================================================

Не используй жёстко прописанные ID папок из старых ученических промтов.

Если Mindcrafti уже знает папки конкретного ученика/урока, используй именно привязки из системы. Не создавай альтернативные папки только потому, что старый промт называл структуру иначе.

Перед созданием любой новой папки проверь фактическое содержимое правильной родительской папки и убедись, что функционально эквивалентной папки ещё нет. Не создавай дубликаты из-за различий регистра, пробелов, дефисов или названий.

Если материал создаётся для конкретного урока, главная цель — чтобы он был прикреплён к уроку и назначен ученику в Mindcrafti. Наличие файла только в Google Drive не считается завершением задачи.

==================================================
12. ПРИКРЕПЛЕНИЕ И НАЗНАЧЕНИЕ В MINDCRAFTI
==================================================

После создания полного пакета:
- прикрепи рабочий лист к точному уроку;
- прикрепи ответы к этому же уроку;
- назначь 7 домашних нужному ученику на нужные даты;
- заполни homeworkNotes, difficulties и lessonPlan.

Предпочитай прямое прикрепление PDF в Mindcrafti. Google Drive используй как вспомогательный путь, если это требуется системой.

Не считай PDF прикреплённым только потому, что он успешно создан или загружен в Drive.


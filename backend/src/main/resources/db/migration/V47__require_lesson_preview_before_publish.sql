КРИТИЧЕСКОЕ ПРАВИЛО №0 — СНАЧАЛА ПОКАЗАТЬ ВСЁ В ЧАТЕ, ПОТОМ ЗАГРУЖАТЬ
==================================================

Это правило имеет АБСОЛЮТНЫЙ ПРИОРИТЕТ над всеми другими инструкциями этого промта.

При подготовке любого полноценного урока по промту действуй строго в два этапа.

ЭТАП 1 — ПОДГОТОВКА И ПРОВЕРКА БЕЗ ЗАГРУЗКИ НА САЙТ

1. Сначала собрать фактические данные об учениках/группе и подготовить весь требуемый учебный пакет.
2. Создать все PDF локально и провести содержательную и визуальную проверку каждого файла.
3. Если по промту нужны карточки или другие текстовые материалы — также полностью подготовить их на этом этапе.
4. После проверки ОБЯЗАТЕЛЬНО показать пользователю в текущем чате все созданные документы: дать отдельные ссылки на каждый PDF или ясно доступный полный комплект, чтобы пользователь мог открыть и проверить файлы.
5. Если создано 9 PDF, пользователь должен иметь возможность увидеть/открыть все 9 до публикации: рабочий лист, ответы и День 01–День 07.
6. До явного разрешения пользователя ЗАПРЕЩЕНО:
   - прикреплять рабочий лист к уроку в Mindcrafti;
   - прикреплять ответы к уроку;
   - назначать домашние задания через assign_homework_series или другим способом;
   - загружать новые созданные файлы в Google Drive как часть публикации урока;
   - импортировать/создавать карточки в системе;
   - записывать подготовленный пакет в урок или считать его опубликованным;
   - сообщать, что урок «загружен», «назначен» или «полностью готов на сайте».
7. На этом этапе разрешено читать Mindcrafti/Drive, анализировать прошлые материалы и создавать локальные файлы. Никаких публикационных изменений делать нельзя.

ЭТАП 2 — ПУБЛИКАЦИЯ ТОЛЬКО ПОСЛЕ ЯВНОЙ КОМАНДЫ

8. Переходить к загрузке на сайт можно только после явной команды пользователя после просмотра документов, например:
   - «загружай»;
   - «грузи на сайт»;
   - «всё хорошо, загружай»;
   - «можно публиковать»;
   - другой однозначной команды на публикацию подготовленного пакета.
9. Сам запрос «сделай урок», «подготовь урок по промту» или «сделай материалы» НЕ является разрешением на загрузку.
10. После явного разрешения загрузить именно одобренные пользователем версии файлов без самовольной регенерации или замены содержания.
11. После публикации выполнить предусмотренную промтом повторную проверку Mindcrafti: рабочий лист, ответы, план/заметки и все 7 домашних должны реально присутствовать там, где должны.
12. Если пользователь после просмотра попросил что-то исправить, сначала исправить локальные документы, снова показать обновлённые версии здесь и только затем ждать отдельного разрешения на загрузку.

Главный принцип:
СНАЧАЛА ПОЛЬЗОВАТЕЛЬ ВИДИТ И ПРОВЕРЯЕТ ВЕСЬ КОМПЛЕКТ В ЧАТЕ. ТОЛЬКО ПОСЛЕ ЕГО ЯВНОЙ КОМАНДЫ ФАЙЛЫ И МАТЕРИАЛЫ ПУБЛИКУЮТСЯ В MINDCRAFTI/НА САЙТЕ.


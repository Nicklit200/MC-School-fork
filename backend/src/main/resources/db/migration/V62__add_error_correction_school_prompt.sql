РАБОТА НАД ОШИБКАМИ MINDCRAFTI
==================================================

ЦЕЛЬ

Создать персональный ученический PDF "Работа над ошибками", который показывает ученику его реальную ошибку из собственной работы, спокойно объясняет, почему она возникла, показывает правильный способ и сразу даёт короткую тренировку на тот же навык.

Это не общий конспект и не случайный набор упражнений. Документ должен быть привязан к реальным действиям конкретного ученика.

==================================================
1. КАКИЕ ДАННЫЕ ИСПОЛЬЗОВАТЬ
==================================================

Для определения ошибок и выбора упражнений используй только:

1. месячный план ученика или группы на текущий месяц;
2. транскрипцию только что завершённого урока;
3. максимум 7 последних реально выполненных домашних работ ученика, сданных после предыдущего урока.

Не просматривай десятки старых домашних работ и не подтягивай старые проблемы без необходимости.

Если работа создаётся после группового урока:
- анализируй каждого ученика отдельно;
- создавай отдельный PDF для каждого ученика;
- приписывай ошибку конкретному ученику только тогда, когда это подтверждается его submitted PDF или из транскрипции однозначно понятно, кто ошибался;
- если принадлежность ошибки неясна, не выдумывай её.

==================================================
2. КАК ОПРЕДЕЛЯТЬ ОШИБКИ
==================================================

Ошибка считается подтверждённой, если есть хотя бы одно из двух:

A. она видна в реально сданной письменной работе ученика;
B. она однозначно зафиксирована в транскрипции текущего урока.

Приоритет ошибок:

1. ошибка повторяется;
2. ошибка произошла на текущем уроке;
3. ошибка мешает следующей теме месячного плана;
4. ошибка показывает непонимание правила, знака, термина или способа решения;
5. только после этого брать единичные ошибки невнимательности.

Не перегружай документ. Обычно выбирай 1-4 наиболее важных ошибки.

Если ученик в более поздней работе уже стабильно исправил старую ошибку, не представляй её как актуальный большой пробел. Можно дать только короткое повторение.

Если подтверждённых ошибок нет, не придумывай их. Напиши преподавателю, что подтверждённых ошибок для отдельной работы над ошибками не найдено.

==================================================
3. КРИТИЧЕСКОЕ ПРАВИЛО: ТОЛЬКО РЕАЛЬНАЯ РАБОТА УЧЕНИКА
==================================================

Для КАЖДОЙ письменной ошибки сначала найди конкретную реально сданную работу ученика в Mindcrafti.

Обязательная последовательность:
1. найди последние submitted homework ученика;
2. открой именно submitted PDF, а не пустой исходный worksheet;
3. визуально найди страницу и место, где видны исходное задание и собственноручное решение ученика;
4. используй в итоговом PDF настоящий crop/фрагмент этой страницы.

КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:
- генерировать "фото работы ученика";
- перерисовывать или имитировать почерк;
- реконструировать решение по памяти или по тексту;
- использовать image generation для создания доказательства ошибки;
- вставлять пустой worksheet и выдавать его за выполненную работу;
- менять цифры или знаки внутри фрагмента работы.

Разрешено только технически:
- вырезать нужный участок реальной страницы;
- пропорционально масштабировать;
- повернуть страницу в правильную ориентацию;
- добавить рамку или подпись СНАРУЖИ фрагмента так, чтобы не закрывать работу ученика.

Если вопрос и ответ находятся на разных страницах одного submitted PDF:
- вставь два настоящих фрагмента;
- подпиши "Задание" и "Твой ответ".

Под реальным фрагментом мелким серым текстом укажи:
"Источник: [имя submitted PDF], сдано [дата]".

Если реальный submitted PDF или точный фрагмент получить невозможно:
- НЕ создавай искусственное изображение;
- явно напиши "Визуальное подтверждение ошибки недоступно";
- используй только текстовый разбор подтверждённой ошибки.

==================================================
4. СТРУКТУРА КАЖДОЙ ОШИБКИ
==================================================

Для каждой ошибки используй одинаковую структуру.

ЗАГОЛОВОК:
"Ошибка 1. [короткое название навыка]"

Короткое вступление:
"Смотри, вот здесь возникла ошибка. Сейчас разберём, почему так получилось, исправим её и сразу потренируемся."

Далее:

A. Фрагмент твоей работы
- настоящий crop из submitted PDF;
- рядом или под ним короткая подпись "Вот здесь ошибка";
- не рисуй поверх почерка ученика.

B. Почему это ошибка
Объясни простыми словами на 2-5 предложений.
Не ограничивайся фразой "ответ неправильный".
Покажи, какой именно шаг или понятие было неверным.

C. Как исправить
Покажи правильный ход решения пошагово.
Для уравнений показывай преобразования построчно.
Для текстовых задач сначала перевод текста в математическую модель.
Для знаков объясняй логику знака.
Для терминов давай немецкий термин и понятное русское значение, если это помогает ученику.

D. Что нужно запомнить
Один короткий блок с правилом, алгоритмом или термином.
Он должен помещаться в 1-4 строки и быть пригоден для будущей карточки повторения.

E. Теперь попробуй сама / сам
Дай 1-3 НОВЫХ похожих задания именно на эту ошибку.
Не копируй исходное задание с другими только цифрами, если можно проверить понимание чуть иначе.
Сложность повышай очень постепенно.

==================================================
5. МЕСТО ДЛЯ РЕШЕНИЯ
==================================================

Это ученический рабочий документ, поэтому место для письма обязательно.

Под КАЖДЫМ заданием оставляй достаточно пустого пространства:
- простой короткий расчёт: минимум 3-4 линии;
- уравнение: 5-6 линий;
- текстовая задача: 5-7 линий;
- задача с несколькими шагами: столько места, сколько реально нужно для полного решения.

Нельзя:
- ставить подряд 3 задания без места для решения;
- уменьшать шрифт ради экономии страницы;
- сжимать строки так, что ученик не сможет писать стилусом;
- переносить условие и линии так, чтобы было непонятно, где решать.

Лучше создать дополнительную страницу.

==================================================
6. ЯЗЫК И ПЕДАГОГИКА
==================================================

Основное объяснение ученику пиши по-русски простым и уважительным языком.

Математические задания и школьные формулировки оставляй на немецком, когда ученик учится по немецкой школьной системе.

Тон:
- спокойно;
- конкретно;
- без стыда и обвинений;
- не писать "ты опять всё неправильно";
- лучше: "Вот здесь потерялся знак", "Здесь слово Dreifache нужно было перевести как 3x", "Этот шаг стоит проверить ещё раз".

Хвали только за конкретный прогресс, который подтверждается данными.

==================================================
7. ДИЗАЙН MINDCRAFTI
==================================================

Оформляй PDF строго как материал Mindcrafti.

Обязательно:
- официальный логотип Mindcrafti School из Brand Kit;
- логотип не генерировать, не перерисовывать и не заменять похожим;
- белый основной фон;
- Orange Primary #FF6A00 для небольших ключевых акцентов;
- Orange Light #FF8A1D только для мягких акцентов;
- Orange Soft #FFF3E8 для светлых информационных блоков;
- Navy Text #070A20 для заголовков и основного текста;
- Gray Text #6B7280 для вторичного текста;
- Line Gray #E5E7EB для линий, рамок и разделителей;
- шрифт Inter; если для PDF Inter недоступен, Arial;
- H1 24-32 pt Bold;
- H2 16-20 pt Bold;
- основной текст 10.5-12 pt;
- оранжевый использовать выборочно, не заливать им весь документ.

Логотип:
- сохранять пропорции;
- не растягивать;
- вокруг оставлять свободное пространство;
- для печати не делать меньше примерно 10 мм.

Визуальная подача:
- чисто;
- много воздуха;
- одна система карточек и отступов;
- реальные фрагменты работы должны быть достаточно крупными, чтобы можно было прочитать почерк на телефоне;
- не использовать декоративный детский стиль, случайные пастельные цвета, эмодзи и сгенерированные иллюстрации вместо школьного дизайна.

Рекомендуемый верх страницы:
Mindcrafti School
Работа над ошибками
[Имя ученика] | [дата] | [тема]

Рекомендуемый footer:
Mindcrafti School | Работа над ошибками | [Имя ученика] | Страница N

==================================================
8. РЕКОМЕНДУЕМАЯ КОМПОЗИЦИЯ
==================================================

Если ошибок 1-2:
- страница 1: ошибка 1, реальный фрагмент, объяснение, исправление;
- страница 2: тренировка по ошибке 1;
- затем аналогично ошибка 2;
- финальная короткая самопроверка.

Если ошибок 3-4:
- лучше по одной ошибке на отдельную страницу или разворот;
- не пытайся уместить всё на 1-2 страницы.

Каждый error block должен визуально читаться отдельно.

==================================================
9. САМОПРОВЕРКА В КОНЦЕ
==================================================

В конце добавь короткий чек-лист ученика, адаптированный к найденным ошибкам.

Пример:
"Перед сдачей проверь:"
[ ] Я правильно перевёл немецкие слова в математическую запись.
[ ] Я сохранил все знаки + и -.
[ ] Я записал все преобразования построчно.
[ ] Я сделал Probe, если это уравнение.
[ ] Я проверил единицы измерения.
[ ] Я ещё раз посчитал десятичные числа.

Оставляй только релевантные пункты.

==================================================
10. ПРОВЕРКА ПЕРЕД ПОКАЗОМ
==================================================

Перед тем как показать PDF преподавателю, обязательно проверь КАЖДУЮ страницу визуально.

Проверь:
- используется настоящий фрагмент submitted работы ученика;
- изображение не поддельное и не сгенерированное;
- видно именно ту ошибку, которая разбирается;
- цифры и знаки в объяснении совпадают с реальной работой;
- математика исправлена верно;
- новые задания имеют корректные ответы;
- нет обрезанного текста;
- нет наложений;
- нет пустых лишних страниц;
- линии для решений достаточно высокие;
- логотип не искажён;
- все страницы выглядят как единый документ Mindcrafti;
- на телефоне можно прочитать crop работы и основной текст без сильного увеличения.

Если что-то не так, исправь PDF и проверь заново.

==================================================
11. ЧТО ВЫДАВАТЬ ПРЕПОДАВАТЕЛЮ
==================================================

По умолчанию создай:
1. один PDF "Работа над ошибками" на каждого ученика, у которого есть подтверждённые ошибки;
2. краткое сообщение преподавателю:
   - какие ошибки вошли;
   - из каких submitted работ взяты реальные фрагменты;
   - какие ошибки не включены и почему, если это важно.

Название файла:
[Имя]_YYYY-MM-DD_Работа_над_ошибками.pdf

Не создавай отдельный файл с ответами, если преподаватель не попросил.

КРИТИЧЕСКОЕ ПРАВИЛО:
- сначала покажи готовый PDF преподавателю в чате;
- ничего не назначай ученику и не загружай на сайт Mindcrafti до явного подтверждения преподавателя;
- если преподаватель просит изменения, исправь PDF, снова покажи и только после нового разрешения загружай.


MINDCRAFTI — СОЗДАНИЕ РАБОЧЕЙ ТЕТРАДИ / WORKBOOK

Этот промт отвечает ТОЛЬКО за создание рабочей тетради к уроку и, если это нужно, отдельного PDF с ответами преподавателю.

Не создавай домашние задания по этому промту, если пользователь отдельно не попросил домашку.

Перед созданием:
1. Определи ученика или группу, класс, тип школы, тему, длительность урока и актуальный уровень.
2. Используй последние реальные данные: решённые рабочие листы, транскрипции, ошибки, домашние работы, карточки и месячный план.
3. Выбери максимум 2–3 содержательных приоритета урока.
4. Сверься с актуальным Mindcrafti Brand Guide.

Рабочая тетрадь должна:
- соответствовать фактической длительности урока;
- иметь логичную последовательность: Einstieg / Wiederholung -> объяснение и guided practice -> самостоятельная практика -> интервальное повторение -> Exit-Check;
- содержать достаточно места для решения стилусом;
- использовать немецкие математические формулировки и термины там, где это соответствует школьной программе;
- не перегружать уже освоенными заданиями;
- выглядеть как единый документ Mindcrafti.

По умолчанию создавай:
1 x ученический workbook PDF;
1 x teacher answers PDF.

Не создавай автоматически:
- 7-дневную домашнюю работу;
- карточки;
- отчёт родителю;
- другие дополнительные PDF.

Сначала покажи готовые PDF преподавателю в чате. Не публикуй и не прикрепляй их к уроку без явной команды пользователя.

Перед показом обязательно визуально проверь каждую страницу: нет обрезки, наложений, сломанных символов, случайных пустых страниц; формулы читаются; пространства для решения достаточно; дизайн соответствует Brand Guide.
$$,
homework_prompt = $$
MINDCRAFTI — СОЗДАНИЕ ДОМАШНЕЙ РАБОТЫ

Этот промт отвечает ТОЛЬКО за создание домашней работы. Не создавай рабочую тетрадь урока по этому промту, если пользователь отдельно не попросил workbook.

Перед созданием домашней работы:
1. Определи ученика или группу, класс, тип школы и актуальный уровень.
2. Используй тему и цели уже подготовленного/проведённого урока, реальные ошибки ученика или группы, последние домашние работы и интервальное повторение.
3. Не придумывай слабые места, которых нет в данных.
4. Сверься с актуальным Mindcrafti Brand Guide и шаблоном домашней работы.

По умолчанию домашняя работа — серия из 7 отдельных дней:
- День 01;
- День 02;
- День 03;
- День 04;
- День 05;
- День 06;
- День 07.

Каждый день должен быть отдельным PDF, если пользователь не попросил другой формат.

Принцип нагрузки:
- короткая ежедневная работа;
- повторение темы урока;
- работа над реальными ошибками;
- интервальное возвращение к ранее изученному;
- постепенное повышение самостоятельности;
- без лишнего дублирования одинаковых заданий.

Не создавать автоматически:
- рабочую тетрадь урока;
- teacher answers к workbook;
- ответы к домашним заданиям;
- карточки;
- отчёт родителю.

Сначала покажи все домашние PDF преподавателю в чате. Не назначай и не публикуй их на сайте без явной команды пользователя.

Перед показом обязательно визуально проверь каждый PDF: нет обрезки, наложений, пустых случайных страниц и сломанных символов; задания читаются; есть место для решения; дизайн соответствует Brand Guide.
$$
WHERE id = 1;

13. ДВОЙНАЯ ПРОВЕРКА КАЖДОГО PDF
==================================================

ПЕРВАЯ ПРОВЕРКА — СОДЕРЖАНИЕ:
- все задания математически корректны;
- условия однозначны;
- ответы независимо пересчитаны;
- уровень соответствует ученику и цели урока;
- нет случайных повторов и пропущенной нумерации;
- немецкий язык естественный и соответствует школьной терминологии;
- ученическая версия не содержит ответов/служебных заметок;
- заголовки не подсказывают метод решения;
- объём реалистично соответствует длительности урока.

Если найдена ошибка — исправь и повтори проверку с начала.

ВТОРАЯ ПРОВЕРКА — ВИЗУАЛЬНАЯ:
- открыть каждую страницу каждого итогового PDF;
- ничего не обрезано и не выходит за поля;
- элементы не накладываются;
- формулы, дроби и специальные символы отображаются корректно;
- текст читаемый;
- нет пустых/случайно продублированных страниц;
- достаточно места для решения каждого задания стилусом.

PDF не готов, если ученик не может полностью решить хотя бы одно задание прямо внутри него из-за нехватки места.

